package datawave.query.transformer;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertNull;
import static org.junit.Assert.assertTrue;

import java.util.AbstractMap;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Set;
import java.util.TreeMap;
import java.util.stream.Collectors;

import org.apache.accumulo.core.data.Key;
import org.apache.accumulo.core.data.Value;
import org.apache.accumulo.core.iteratorsImpl.system.SortedMapIterator;
import org.apache.hadoop.io.Text;
import org.junit.Before;
import org.junit.Test;

import com.google.common.collect.ArrayListMultimap;
import com.google.common.collect.Multimap;

import datawave.ingest.protobuf.TermWeight;
import datawave.query.Constants;
import datawave.query.attributes.Attribute;
import datawave.query.attributes.Attributes;
import datawave.query.attributes.Content;
import datawave.query.attributes.Document;
import datawave.query.attributes.ExcerptFields;
import datawave.query.function.JexlEvaluation;
import datawave.query.iterator.logic.TermFrequencyExcerptIterator;
import datawave.query.postprocessing.tf.PhraseIndexes;

/**
 * Tests for {@link ExcerptTransform}. Rather than mocking the iterator and source, these tests drive a real {@link TermFrequencyExcerptIterator} backed by a
 * {@link SortedMapIterator} over real term-frequency data, with real {@link Document} instances. The excerpts are therefore generated by the real code path
 * (both the hit-term offset resolution in {@code getOffset} and the excerpt generation in the iterator) rather than scripted on a mock.
 */
public class ExcerptTransformTest {

    // the document under test: row=shard, cf=dt\0uid, so the event id is shard\0dt\0uid
    private static final String DATATYPE = "dt";
    private static final String UID = "uid";
    private static final Text SHARD = new Text("shard");
    private static final Key DOC_KEY = new Key(SHARD, new Text(DATATYPE + Constants.NULL + UID));
    // the event id as computed by ExcerptTransform.keyToEventId(DOC_KEY): row + NUL + columnFamily
    private static final String EVENT_ID = "shard" + Constants.NULL + DATATYPE + Constants.NULL + UID;

    // accumulated term frequencies, keyed by "field\0value" -> list of {offset, prevSkip}
    private final Multimap<String,int[]> termFrequencies = ArrayListMultimap.create();
    private PhraseIndexes phraseIndexes;
    private ExcerptFields excerptFields;

    private Document document;
    private ExcerptTransform excerptTransform;

    @Before
    public void setUp() {
        termFrequencies.clear();
        phraseIndexes = new PhraseIndexes();
        excerptFields = new ExcerptFields();
    }

    /**
     * Verify that a null entry is returned for a null input.
     */
    @Test
    public void testNullDocumentEntry() {
        initTransform();
        assertNull(excerptTransform.apply(null));
    }

    /**
     * Verify that excerpts are not added for documents that are not marked as to-keep.
     */
    @Test
    public void testNonToKeepDocumentEntry() {
        document = new Document(DOC_KEY, false);
        initTransform();

        applyTransform();

        assertFalse(document.containsKey(ExcerptTransform.HIT_EXCERPT));
    }

    /**
     * Verify that excerpts are not added for documents that have no phrase indexes or hit terms.
     */
    @Test
    public void testNullPhraseIndexes() {
        document = new Document(DOC_KEY, true);
        initTransform();

        applyTransform();

        assertFalse(document.containsKey(ExcerptTransform.HIT_EXCERPT));
    }

    /**
     * Verify that excerpts are retrieved with the expected inputs.
     */
    @Test
    public void testExcerpts() {
        // Setup our excerpts to match 2 words on either side of the BODY
        givenExcerptField("BODY", 2);

        // setup a matching phrase at 10-14
        // end offset is inclusive
        givenPhraseIndex("BODY", 10, 14);

        // setup a matching term for BODY:word
        givenDocumentWithHitTerm("BODY", "word");
        givenDocumentText("BODY", 22, "and the word from bird");
        givenDocumentText("BODY", 8, "the quick brown fox jumped over the lazy dog");

        initTransform();
        applyTransform();

        Set<String> excerpts = getExcerpts();
        assertEquals(2, excerpts.size());
        // the excerpt around the phrase index [10,14] (+/- 2 -> offsets 8..16)
        assertTrue(excerpts.contains("the quick brown fox jumped over the lazy dog"));
        // the excerpt around the hit term BODY:word at offset 24 (+/- 2 -> offsets 22..26)
        assertTrue(excerpts.contains("and the [word] from bird"));
    }

    /**
     * Verify that excerpts are retrieved with the expected inputs.
     */
    @Test
    public void testExcerptOverlapped() {
        // Setup our excerpts to match 2 words on either side of the BODY
        givenExcerptField("BODY", 2);

        // setup a matching phrase at 10-14
        // end offset is inclusive
        givenPhraseIndex("BODY", 10, 14);

        // setup a matching term for BODY:quick brown overlapping the phrase match
        givenDocumentWithHitTerm("BODY", "quick brown");
        givenTermFrequencies("BODY", new int[][] {{1, 2}, {2, 3}, {9, 10}, {20, 21}}, "quick brown");
        // note that the start is relative to index 9 (i.e. 9-2=7) because the overlapping term starts at 9
        givenDocumentText("BODY", 7, "and the quick brown fox jumped over the lazy dog");

        initTransform();
        applyTransform();

        Set<String> excerpts = getExcerpts();
        // the hit term's offset (9-10) overlaps the phrase index [10,14], so they merge into a single excerpt. The
        // longest token at the overlapping offset ("quick brown") is bracketed by the iterator's longest-word rule.
        assertEquals(1, excerpts.size());
        assertTrue(excerpts.contains("and the [quick] [quick brown] fox jumped over the lazy dog"));
    }

    /**
     * Verify that excerpts are retrieved with the expected inputs.
     */
    @Test
    public void testExcerptOverlappedAndPhraseOverlapped() {
        // Setup our excerpts to match 2 words on either side of the BODY
        givenExcerptField("BODY", 2);

        // setup a matching phrase at 10-14, ...
        // end offset is inclusive
        givenPhraseIndex("BODY", 10, 14);
        givenPhraseIndex("BODY", 25, 26);
        givenPhraseIndex("BODY", 4, 5);

        // setup a matching term for BODY:quick brown overlapping the phrase match
        givenDocumentWithHitTerm("BODY", "quick brown");
        givenTermFrequencies("BODY", new int[][] {{1, 2}, {2, 3}, {9, 10}, {20, 21}}, "quick brown");
        givenDocumentText("BODY", 23, "Jack and Jill jumped over the");
        // note that the start is relative to overlapping term index 9 (i.e. 9-2=7) because the overlapping term starts at 9
        // AND then we combined the phrase from 2 to 7 with the one from 7 to 16
        givenDocumentText("BODY", 2, "the brown chicken layed an egg and the quick brown fox jumped over the lazy dog");

        initTransform();
        applyTransform();

        Set<String> excerpts = getExcerpts();
        // the hit term overlaps phrase index [10,14] and merges with it; that merged window then overlaps the expanded
        // window of phrase index [4,5], so they combine into a single excerpt. Phrase index [25,26] is far enough away
        // to remain its own excerpt. The result is two excerpts.
        assertEquals(2, excerpts.size());
        assertTrue(excerpts.contains("Jack and Jill jumped over the"));
        assertTrue(excerpts.contains("quick brown [quick brown] chicken layed an egg and the [quick brown] [brown] fox jumped over the lazy"));
    }

    /**
     * Verify that when a start index is less than the specified excerpt offset, that the excerpt start defaults to 0.
     */
    @Test
    public void testOffsetGreaterThanStartIndex() {
        givenExcerptField("CONTENT", 2);
        // end offset is inclusive
        givenPhraseIndex("CONTENT", 1, 5);

        givenDocumentWithPhraseIndexesOnly();
        givenDocumentText("CONTENT", 0, "the quick brown fox jumped over the lazy dog");

        initTransform();
        applyTransform();

        Set<String> excerpts = getExcerpts();
        // phrase index [1,5] with offset 2 would start at -1, which is clamped to 0, so the excerpt covers offsets 0..7
        assertEquals(1, excerpts.size());
        assertTrue(excerpts.contains("the quick brown fox jumped over the lazy"));
    }

    /**
     * Verify that a phrase index with the end before the start does not mess us up
     */
    @Test
    public void testEmptyPhraseIndexes() {
        // Setup our excerpts to match 2 words on either side of the BODY
        givenExcerptField("BODY", 2);

        // setup a matching term for BODY:word with no phrase indexes
        givenDocumentWithHitTerm("BODY", "word");
        givenDocumentText("BODY", 22, "and the word from bird");

        initTransform();
        applyTransform();

        Set<String> excerpts = getExcerpts();
        // with no phrase indexes, the excerpt is generated solely from the hit term BODY:word at offset 24
        assertEquals(1, excerpts.size());
        assertTrue(excerpts.contains("and the [word] from bird"));
    }

    private void initTransform() {
        TreeMap<Key,Value> data = new TreeMap<>();
        for (String fieldAndValue : termFrequencies.keySet()) {
            int split = fieldAndValue.indexOf(Constants.NULL);
            String field = fieldAndValue.substring(0, split);
            String value = fieldAndValue.substring(split + 1);

            List<int[]> occurrences = new ArrayList<>(termFrequencies.get(fieldAndValue));
            occurrences.sort((a, b) -> Integer.compare(a[0], b[0]));

            TermWeight.Info.Builder builder = TermWeight.Info.newBuilder();
            for (int[] occurrence : occurrences) {
                builder.addTermOffset(occurrence[0]);
                builder.addPrevSkips(occurrence[1]);
                builder.addScore(-1);
            }

            Text colq = new Text(DATATYPE + Constants.NULL + UID + Constants.NULL + value + Constants.NULL + field);
            data.put(new Key(SHARD, Constants.TERM_FREQUENCY_COLUMN_FAMILY, colq), new Value(builder.build().toByteArray()));
        }

        SortedMapIterator source = new SortedMapIterator(data);
        excerptTransform = new ExcerptTransform(excerptFields, null, source, new TermFrequencyExcerptIterator());
    }

    private void applyTransform() {
        excerptTransform.apply(new AbstractMap.SimpleEntry<>(new Key(), document));
    }

    private void givenExcerptField(String field, int offset) {
        excerptFields.put(field, offset);
    }

    private void givenPhraseIndex(String field, int start, int end) {
        // end offset is inclusive
        phraseIndexes.addIndexTriplet(field, EVENT_ID, start, end);
    }

    /** Build a document carrying the accumulated phrase indexes and a single {@code field:value} hit term. */
    private void givenDocumentWithHitTerm(String field, String value) {
        document = new Document(DOC_KEY, true);
        document.put(ExcerptTransform.PHRASE_INDEXES_ATTRIBUTE, new Content(phraseIndexes.toString(), DOC_KEY, false));

        List<Attribute<? extends Comparable<?>>> hits = new ArrayList<>();
        hits.add(new Content(field + ":" + value, DOC_KEY, true));
        document.put(JexlEvaluation.HIT_TERM_FIELD, new Attributes(hits, true));
    }

    /** Build a document carrying the accumulated phrase indexes and no hit terms. */
    private void givenDocumentWithPhraseIndexesOnly() {
        document = new Document(DOC_KEY, true);
        document.put(ExcerptTransform.PHRASE_INDEXES_ATTRIBUTE, new Content(phraseIndexes.toString(), DOC_KEY, false));
    }

    /**
     * Add term frequencies for the document text, where each whitespace-delimited token occupies the offset matching its position relative to startOffset.
     * Bracket markers used to denote hit terms in the original assertions are stripped.
     */
    private void givenDocumentText(String field, int startOffset, String text) {
        String[] tokens = text.split(" ");
        for (int i = 0; i < tokens.length; i++) {
            String token = tokens[i].replace("[", "").replace("]", "");
            int offset = startOffset + i;
            termFrequencies.put(field + Constants.NULL + token, new int[] {offset, 0});
        }
    }

    /**
     * Add a single term-frequency entry for the given field and value, preserving the exact offsets and previous-skip values. Each pair is {@code {lowOffset,
     * offset}}, matching the original test inputs.
     */
    private void givenTermFrequencies(String field, int[][] offsets, String value) {
        for (int[] offset : offsets) {
            termFrequencies.put(field + Constants.NULL + value, new int[] {offset[1], offset[1] - offset[0]});
        }
    }

    private Set<String> getExcerpts() {
        if (!document.containsKey(ExcerptTransform.HIT_EXCERPT)) {
            return Collections.emptySet();
        }
        Attributes attributes = (Attributes) document.get(ExcerptTransform.HIT_EXCERPT);
        return attributes.getAttributes().stream().map(a -> a.getData().toString()).collect(Collectors.toSet());
    }
}
